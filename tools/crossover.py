def _caixa(cls, titulo, intro, itens):
    lis = ''.join(f'<li><a href="{u}" target="_blank" rel="noopener">{t}</a></li>' for u, t in itens)
    return f'<div class="wrap estreito secao" style="padding-top:0"><aside class="nota cruzada {cls}" aria-label="{titulo}"><strong>{titulo}</strong><p>{intro}</p><ul>{lis}</ul></aside></div>'

def caixa_politica(path, esc):
    """Para páginas da Política: textos da Ética que aprofundam a discussão moral."""
    its = [(f'{SITE_ETI}/{b}', esc(TITULOS_ETI[b])) for a, b in PARES if a == path]
    if not its: return ''
    return _caixa('para-etica', 'Para aprofundar o debate ético', 'Este tema também envolve uma pergunta moral de fundo. O site irmão Ética Para Iniciantes discute isso com mais calma:', its)

def caixa_etica(path, esc):
    """Para páginas da Ética: o lado político do mesmo tema, no Política Para Iniciantes."""
    its = [(f'{SITE_POL}/{a}', esc(TITULOS_POL[a])) for a, b in PARES if b == path]
    if not its: return ''
    return _caixa('para-politica', 'E na política?', 'Para ver como este tema aparece em leis, governos e eleições no Brasil, veja no site irmão Política Para Iniciantes:', its)
